{-# LANGUAGE OverloadedStrings #-}
module Main (main) where
import Control.Monad (unless)
import qualified Crypto.Hash.SHA256 as SHA
import qualified Data.ByteString as B
import qualified Data.ByteString.Char8 as C
import qualified Data.Text as T
import qualified Data.Text.Encoding as TE
import GHC.Clock (getMonotonicTimeNSec)
import Numeric (showHex)
import System.Directory (copyFile,createDirectory)
import System.Environment (getArgs)
import System.FilePath ((</>),takeDirectory)
import qualified System.Posix.Files as P
import Warlock.Backend
import Warlock.Bootstrap (BootstrapResult(..))
import Warlock.Capture.Process.Bootstrap
import Warlock.Protocol.Identity (parseCounter,renderCounter)
import qualified Warlock.Protocol.Desktop as D
import Warlock.Protocol.StrictJson (Json(..),renderJson)

check :: String -> Bool -> IO ()
check name good = unless good (ioError (userError name))
must :: Show e => Either e a -> IO a
must = either (ioError . userError . show) pure
js :: String -> Json
js = JString . T.pack
decimal :: Integral a => a -> Json
decimal = js . show . toInteger
hex :: B.ByteString -> B.ByteString
hex = C.pack . concatMap (\n -> let s=showHex n "" in if length s==1 then '0':s else s) . B.unpack
hash :: B.ByteString -> Json
hash = JString . TE.decodeUtf8 . hex . SHA.hash
privateDirectory :: FilePath -> IO ()
privateDirectory path = createDirectory path >> P.setFileMode path 0o700
directory :: FilePath -> IO Json
directory path = do
 s <- P.getSymbolicLinkStatus path
 check "directory is physical" (P.isDirectory s && not (P.isSymbolicLink s))
 pure (JObject [("path",js path),("device",decimal (P.deviceID s)),("inode",decimal (P.fileID s))])
ancestors :: FilePath -> [FilePath]
ancestors path | path=="/" = []
               | otherwise = ancestors (takeDirectory path) ++ [path]
-- These two fixed desktop sources are independent literal inputs, not output
-- generated by the production parser or catalog reducer.
source :: B.ByteString
source = "[Desktop Entry]\nType=Application\nName=Owned Recorder\nExec=fixture-recorder\nTerminal=false\n"
badSource :: B.ByteString
badSource = "[Desktop Entry]\nType=Application\nName=Bad Recorder\nExec=bad-recorder\nTerminal=false\n"
plan :: FilePath -> FilePath -> String -> B.ByteString -> String -> [Json] -> IO Json
plan root filename entry desktop rawExec argv = do
 rs <- P.getSymbolicLinkStatus root
 fs <- P.getSymbolicLinkStatus (root </> filename)
 image <- B.readFile (root </> filename)
 pure (JObject
  [("entry",js entry),("sourceSha256",hash desktop),("exec",js rawExec),("argv",JArray argv)
  ,("root",js root),("rootDevice",decimal (P.deviceID rs)),("rootInode",decimal (P.fileID rs))
  ,("pins",JArray [JObject [("path",js ('/':filename)),("device",decimal (P.deviceID fs)),("inode",decimal (P.fileID fs)),("kind",js "regular")]])
  ,("path",js filename),("links",JArray []),("size",decimal (P.fileSize fs)),("sha256",hash image)])
main :: IO ()
main = do
 args <- getArgs
 (scratch,peerImage,appImage) <- case args of
  [a,b,c] -> pure (a,b,c)
  _ -> ioError (userError "fixed scratch peer-image app-image arguments required")
 let root=scratch </> "owner-route"; cat=root </> "catalog"; pins=root </> "pins"
     images=root </> "images"; peer=images </> "peer"; app=images </> "recorder"
 privateDirectory root
 mapM_ privateDirectory [cat,pins,images]
 copyFile peerImage peer
 copyFile appImage app
 P.setFileMode peer 0o700
 P.setFileMode app 0o700
 B.writeFile (images </> "bad") "literal-not-an-ELF-image\n"
 P.setFileMode (images </> "bad") 0o700
 B.writeFile (cat </> "ux003-recorder.desktop") source
 B.writeFile (cat </> "bad-recorder.desktop") badSource
 P.setFileMode (cat </> "ux003-recorder.desktop") 0o600
 P.setFileMode (cat </> "bad-recorder.desktop") 0o600
 parentPins <- mapM directory (ancestors images)
 cs <- directory cat
 ps <- directory pins
 us <- P.getSymbolicLinkStatus peer
 ub <- B.readFile peer
 good <- plan images "recorder" "ux003-recorder" source "fixture-recorder" [js "two words",js "",js "caf\233"]
 bad <- plan images "bad" "bad-recorder" badSource "bad-recorder" []
 -- The original bootstrap API permits at most thirty seconds. Sample once;
 -- no action, callback or producer can renew this absolute deadline.
 start <- getMonotonicTimeNSec
 let config=JObject
      [("schema",JNumber "1"),("binding",JObject [("lifetime",js "1"),("session",js "2"),("frontend",js "3")])
      ,("deadlineMonotonicNs",decimal (start+30000000000))
      ,("ui",JObject [("path",js peer),("device",decimal (P.deviceID us)),("inode",decimal (P.fileID us)),("size",decimal (P.fileSize us)),("sha256",hash ub),("arguments",JArray []),("ancestors",JArray parentPins)])
      ,("catalogRoots",JArray [cs]),("pinsRoot",ps),("locale",js "C"),("applicationAttachment",JBool True),("applicationPlans",JArray [bad,good])]
     configFile=root </> "startup.json"
 B.writeFile configFile (TE.encodeUtf8 (renderJson config))
 P.setFileMode configFile 0o600
 configured <- loadBackendConfig configFile >>= must
 result <- runBackend configured
 check "actual owned backend completed" (backendPassed result)
 check "all independent cleanup confirmed" (backendCleanup result)
 check "six real admitted callback frames" (backendCallbackCount result==6)
 check "catalog plus two actual launched operations" (backendOperationCount result==3)
 check "no application custody discarded" (backendApplicationCustody result==Nothing)
 check "no notification custody discarded" (backendNotificationCustody result==Nothing)
 case backendBootstrap result of
  Right (Executed selected) -> do
   check "peer normal observed exit" (selectedObservedExit selected==Just 0)
   check "peer actual final custody" (selectedCustody selected==Available)
   case selectedOperation selected of
    Right captured -> check "peer received literal positive/refusal outcomes" (output captured=="application-owner-peer: complete\n" && B.null (diagnostics captured))
    Left _ -> ioError (userError "peer operation failed")
  _ -> ioError (userError "actual bootstrap not executed")
 request <- must (parseCounter False "11")
 case backendApplicationReceipt result of
  Just (identity,selected) -> do
   check "latest genuine request receipt" (identity==request)
   check "application observed exit0" (selectedObservedExit selected==Just 0)
   check "application actual final custody" (selectedCustody selected==Available)
   case selectedOperation selected of
    Right captured -> do
     unless (output captured=="[\"two words\",\"\",\"caf\\233\"]\n" && B.null (diagnostics captured)) $ do
      C.putStrLn ("application-owner-argv-diagnostic stdoutBytes=" <> C.pack (show (B.length (output captured))) <> " stdoutHexPrefix256=" <> hex (B.take 256 (output captured)))
      C.putStrLn ("application-owner-argv-diagnostic stderrBytes=" <> C.pack (show (B.length (diagnostics captured))) <> " stderrHexPrefix256=" <> hex (B.take 256 (diagnostics captured)))
     check "application literal argv receipt" (output captured=="[\"two words\",\"\",\"caf\\233\"]\n" && B.null (diagnostics captured))
    Left _ -> ioError (userError "application operation failed")
  Nothing -> ioError (userError "application receipt missing")
 case backendApplicationObservation result of
  Just (intent,Just published) -> do
   check "diagnostic actual submitted request eleven" (renderCounter (D.launchRequest intent)=="11")
   check "diagnostic actual launch revision one" (renderCounter (D.launchGeneration intent)=="1" && renderCounter (D.launchLifetime intent)=="1")
   check "diagnostic actual selected entry" (D.launchEntry intent=="ux003-recorder")
   check "diagnostic last successful catalog is exact submitted snapshot" (backendCatalogObservation result==Just published)
   encoded <- must (D.encodeDesktopReply published)
   check "diagnostic actual published revision literal" ("\"generation\":\"1\"" `B.isInfixOf` encoded)
   check "diagnostic actual published entry literal" ("\"id\":\"ux003-recorder\"" `B.isInfixOf` encoded)
  _ -> ioError (userError "actual published launch diagnostic missing")
 putStrLn "application-owner-route-controls: complete"
