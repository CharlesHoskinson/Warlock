#!/usr/bin/env python3
"""Compile Warlock token exports and contrast checks deterministically."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
data=json.loads((root/'tokens.json').read_text())
themes=('night','dawn','high-contrast')
def walk(node,path=()):
 if isinstance(node,dict):
  if '$value' in node: yield path,node
  else:
   for k,v in node.items():
    if not k.startswith('$'): yield from walk(v,path+(k,))
def resolve(v,seen=()):
 if isinstance(v,str) and v.startswith('{') and v.endswith('}'):
  path=v[1:-1]
  if path in seen: raise ValueError('Alias cycle: '+path)
  node=data
  try:
   for part in path.split('.'): node=node[part]
   return resolve(node['$value'],seen+(path,))
  except (KeyError,TypeError) as e: raise ValueError('Unresolved alias: '+path) from e
 if isinstance(v,dict): return {k:resolve(x,seen) for k,x in v.items()}
 if isinstance(v,list): return [resolve(x,seen) for x in v]
 return v
def number(v):
 if isinstance(v,bool) or not isinstance(v,(int,float)): raise ValueError('Expected number: '+repr(v))
 return str(v) if isinstance(v,int) else repr(v)
def dim(v,units):
 if not isinstance(v,dict) or set(v)!={'value','unit'} or v['unit'] not in units: raise ValueError('Invalid dimension: '+repr(v))
 return number(v['value'])+v['unit']
def color(v):
 if not isinstance(v,dict) or v.get('colorSpace')!='srgb' or len(v.get('components',[]))!=3 or any(not isinstance(c,(int,float)) or not 0<=c<=1 for c in v['components']): raise ValueError('Invalid color: '+repr(v))
 alpha=v.get('alpha',1)
 if not isinstance(alpha,(int,float)) or not 0<=alpha<=1: raise ValueError('Invalid alpha')
 h=v.get('hex','')
 if not __import__('re').fullmatch(r'#[0-9a-fA-F]{6}',h) or any(abs(int(h[1+i*2:3+i*2],16)/255-c)>1e-8 for i,c in enumerate(v['components'])): raise ValueError('Invalid color hex: '+repr(v))
 if alpha==0: return 'transparent'
 if alpha==1: return h.upper()
 return 'rgb('+ ' '.join(str(round(c*255)) for c in v['components'])+' / '+number(alpha)+')'
def cssval(typ,v):
 v=resolve(v)
 if typ=='color': return color(v)
 if typ=='dimension': return dim(v,('px','rem'))
 if typ=='duration': return dim(v,('ms','s'))
 if typ in ('number','fontWeight'): return number(v)
 if typ=='fontFamily':
  if not isinstance(v,list) or not v or any(not isinstance(x,str) or not x for x in v): raise ValueError('Invalid font family')
  return ', '.join("'"+x+"'" if ' ' in x else x for x in v)
 if typ=='shadow':
  if not isinstance(v,list): raise ValueError('Invalid shadow')
  return ', '.join(' '.join([dim(x[k],('px','rem')) for k in ('offsetX','offsetY','blur','spread')]+[color(x['color'])]) for x in v) or 'none'
 if typ=='typography':
  if not isinstance(v,dict) or set(v)!={'fontFamily','fontSize','lineHeight','fontWeight','letterSpacing'}: raise ValueError('Invalid typography')
  return {'family':cssval('fontFamily',v['fontFamily']),'size':cssval('dimension',v['fontSize']),'line-height':cssval('number',v['lineHeight']),'weight':cssval('fontWeight',v['fontWeight']),'tracking':cssval('dimension',v['letterSpacing'])}
 raise ValueError('Unknown token type: '+str(typ))
def declarations(prefix,path,t):
 val=cssval(t.get('$type'),t['$value']); name=prefix+'-'.join(path)
 if isinstance(val,dict): return ''.join(f'    {name}-{k}: {v};\n' for k,v in val.items())
 return f'    {name}: {val};\n'
# Validate every token and nested alias before producing any outputs.
for _,token in walk(data): cssval(token.get('$type'),token['$value'])
css='/* Generated by authoring/compile.py from tokens.json. */\n@layer tokens {\n'
css+='  html[data-warlock-design="v1"] {\n'
for path,t in walk(data['sys']):
 if path[0] not in themes and path[0]!='shadow': css+=declarations('--wl-sys-',path,t)
css+='  }\n'
for theme in themes:
 css+=f'  html[data-warlock-design="v1"][data-theme="{theme}"], html[data-warlock-design="v1"] [data-theme="{theme}"] {{\n'
 for path,t in walk(data['sys'][theme]): css+=declarations('--wl-sys-',path,t)
 for path,t in walk(data['comp'][theme]): css+=declarations('--wl-comp-',path,t)
 css+='  }\n'
css+='}\n'
def rgb(t,n): return resolve(data['sys'][t]['color'][n]['$value'])['components']
def linear(v): return v/12.92 if v<=.04045 else ((v+.055)/1.055)**2.4
def ratio(a,b,m=None):
 def lum(c):
  c=[linear(x) for x in c]
  if m: c=[max(0,min(1,sum(x*y for x,y in zip(row,c)))) for row in m]
  return sum(x*y for x,y in zip(c,[.2126,.7152,.0722]))
 a,b=sorted([lum(a),lum(b)]); return (b+.05)/(a+.05)
matrices={'protanopia':[[.152286,1.052583,-.204868],[.114503,.786281,.099216],[-.003882,-.048116,1.051998]],'deuteranopia':[[.367322,.860646,-.227968],[.280085,.672501,.047413],[-.01182,.04294,.968881]]}
bgs=['canvas','surface-recessed','surface','surface-raised','surface-hover','surface-pressed','surface-selected','surface-selected-hover','surface-selected-pressed']; fgs=['text','text-secondary','brand-text','focus','info','positive','warning','danger','border-essential']
checks=[]
def add(t,f,b,threshold,usage):
 r=ratio(rgb(t,f),rgb(t,b)); checks.append({'theme':t,'foreground':f,'background':b,'ratio':r,'threshold':threshold,'pass':r>=threshold,'usage':usage,'cvd':{k:ratio(rgb(t,f),rgb(t,b),m) for k,m in matrices.items()}})
for t in themes:
 for f in fgs:
  for b in bgs: add(t,f,b,3 if f=='border-essential' else 4.5,'disabled label and placeholder' if f=='text-secondary' else 'neutral surface')
 for b in ['action-fill','action-fill-hover','action-fill-pressed']: add(t,'on-action',b,4.5,'action text and inner boundary')
 for b in bgs: add(t,'on-action' if t=='night' else 'brand-text' if t=='dawn' else 'action-fill',b,3,'action outer boundary')
 for b in bgs: add(t,'focus',b,3,'focus ring against opaque gap')
 add(t,'window-edge-focused','window-edge-unfocused',3,'focused versus unfocused edge')
out={'method':'WCAG relative luminance, unrounded sRGB; Machado severity 1.0 simulations in linear sRGB with clipping','restrictions':['Use on-action only on filled actions.','Disabled labels and placeholders use text-secondary at full opacity.','Focus gaps use the opaque containing surface.','Color-vision simulations supplement redundant cues and user testing.'],'checks':checks}
failures=[c for c in checks if not c['pass'] or any(v < c['threshold'] for v in c['cvd'].values())]
if failures: raise ValueError('Contrast threshold failed: '+str(failures))
contrast=json.dumps(out,indent=2)+'\n'
import sys
outputs={'tokens.css':css,'contrast.json':contrast}
if sys.argv[1:] == ['--check']:
 for name,content in outputs.items():
  if (root/name).read_text()!=content: raise SystemExit(name+' is out of date')
elif sys.argv[1:]: raise SystemExit('Usage: compile.py [--check]')
else:
 for name,content in outputs.items(): (root/name).write_text(content)

