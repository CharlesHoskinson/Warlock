import assert from 'node:assert/strict';
import {createHost} from './index.js';
const listeners = new Map();
globalThis.location = {origin:'https://example.test'};
globalThis.addEventListener = (kind, callback) => listeners.set(kind,callback);
globalThis.removeEventListener = kind => listeners.delete(kind);
const sent = [];
const frames = Object.fromEntries(['controller','bar','popup'].map(id => [id,{postMessage:(packet,origin) => sent.push({id,packet,origin})}]));
const diagnostics = [];
const host = createHost({frames,onDiagnostic:item => diagnostics.push(item)});
host.start();
assert.equal(sent.length,3);
const receive = listeners.get('message');
const message = (source,origin,packet) => receive({source,origin,data:packet});
const envelope = {bridgeVersion:1,epoch:0,frameId:'controller',kind:'native',payload:JSON.stringify({protocolVersion:3,kind:'host-ready'})};
message(frames.controller,'https://wrong.test',envelope);
message(frames.bar,'https://example.test',envelope);
assert.equal(sent.length,3);
message(frames.controller,'https://example.test',envelope);
assert.ok(sent.some(row => row.packet.payload?.method === 'receiveTopology'));
assert.ok(sent.some(row => row.packet.payload?.value?.kind === 'attached'));
assert.ok(sent.some(row => row.packet.payload?.value?.kind === 'host-geometry-negotiate')); 
assert.ok(sent.some(row => row.packet.payload?.value?.kind === 'pointer-ownership')); 
const native = (id, packet) => message(frames[id], 'https://example.test', {bridgeVersion:1,epoch:0,frameId:id,kind:'native',payload:JSON.stringify(packet)});
for (const id of ['bar','popup']) native(id,{surfaceProtocol:2,kind:'presentation-ready'});
const commit = (publication, mode, focus = []) => native('controller',{viewProtocol:1,kind:'view-commit',projection:{revision:'1',frame:{publication,lease:'1',mode,bar:[{id:'bar:system',domId:`system-${publication}`,enabled:true}],popup:mode==='closed'?[]:[{id:'control:close',domId:`close-${publication}`,enabled:true}]}},requests:[],focus});
commit('1','closed');
native('bar',{surfaceProtocol:2,kind:'presentation-applied',publication:'1',lease:'1'});
native('bar',{surfaceProtocol:2,kind:'surface-action',publication:'1',lease:'1',id:'bar:system'});
commit('2','system');
assert.equal(host.dispatchInput({kind:'outside-press',epoch:0,publication:'1',lease:'1'}),false);
assert.equal(host.dispatchInput({kind:'outside-press',epoch:0,publication:'2',lease:'1'}),true);
assert.deepEqual(sent.at(-1).packet.payload,{method:'receiveDismiss',value:{scope:{id:'1',generation:'1'},lease:'1'}});
commit('3','closed',['old-opener']);
commit('4','closed');
native('bar',{surfaceProtocol:2,kind:'presentation-applied',publication:'3',lease:'1'});
native('bar',{surfaceProtocol:2,kind:'presentation-applied',publication:'4',lease:'1'});
assert.deepEqual(sent.at(-1).packet.payload.value.targets,['system-4']);
commit('5','closed');
native('bar',{surfaceProtocol:2,kind:'focus-applied',publication:'4',lease:'1',targets:['system-4']});
native('bar',{surfaceProtocol:2,kind:'presentation-applied',publication:'5',lease:'1'});
assert.deepEqual(sent.at(-1).packet.payload.value.targets,['system-5']);
native('bar',{surfaceProtocol:2,kind:'focus-applied',publication:'5',lease:'1',targets:['system-5']});
const oldSnapshot = host.getSnapshot();
assert.ok(Object.isFrozen(oldSnapshot.workspaces));
host.reset();
message(frames.controller,'https://example.test',envelope);
assert.equal(diagnostics.filter(x => x.kind === 'controller-ready').length,1);
assert.equal(host.getSnapshot().epoch,1);
assert.throws(() => host.setFault('invalid'),RangeError);
for (const [scale, height] of [[100,56],[125,68],[150,80],[200,104]]) {
  host.reset({appearance:{theme:'night',textScale:scale,effectsOff:false,reducedTransparency:false}});
  host.dispatchInput({kind:'viewport',width:1000,height:700});
  assert.equal(host.getSnapshot().workArea.y,height);
}
host.dispatchInput({kind:'viewport',width:1440,height:900});
let tiled=host.getSnapshot().windows.filter(w=>w.workspace==='1' && !w.minimized);
assert.equal(tiled[0].geometry.x,10);
assert.equal(tiled.at(-1).geometry.x+tiled.at(-1).geometry.width,1430);
assert.equal(tiled[0].geometry.y+tiled[0].geometry.height,890);
const original=host.getSnapshot().windows[0];
const gesture={kind:'pointer',epoch:host.getSnapshot().epoch,windowId:original.id,incarnation:original.incarnation,pointerId:1,mode:'move',x:0,y:0};
assert.equal(host.dispatchInput({...gesture,action:'start'}),true);
host.dispatchInput({...gesture,action:'move',currentX:100,currentY:70});
host.dispatchInput({...gesture,action:'cancel'});
assert.deepEqual(host.getSnapshot().windows[0].geometry,original.geometry);
assert.equal(host.getSnapshot().windows[0].placementMode,original.placementMode);
const snapBefore=host.getSnapshot();
assert.equal(host.dispatchInput({kind:'placement',epoch:snapBefore.epoch-1,windowId:original.id,incarnation:original.incarnation,zone:'left',geometry:{x:10,y:114,width:400,height:700}}),false);
assert.equal(host.dispatchInput({kind:'placement',epoch:snapBefore.epoch,windowId:original.id,incarnation:original.incarnation,zone:'left',geometry:{x:10,y:114,width:400,height:700}}),true);
assert.equal(host.getSnapshot().windows[0].placementMode,'snapped');
assert.deepEqual(host.getSnapshot().windows[0].restoreGeometry,original.geometry);
assert.equal(host.dispatchInput({kind:'placement',epoch:snapBefore.epoch,windowId:original.id,incarnation:'wrong',zone:'maximize',geometry:{x:10,y:114,width:400,height:700}}),false);
host.dispatchInput({kind:'window',action:'minimize',epoch:host.getSnapshot().epoch,windowId:original.id,incarnation:original.incarnation});
tiled=host.getSnapshot().windows.filter(w=>w.workspace==='1' && !w.minimized);
assert.equal(tiled[0].geometry.width,1420);
const count=host.getSnapshot().windows.length;
assert.equal(host.dispatchInput({kind:'application',action:'launch',intent:{entry:'warlock-editor'}}),true);
assert.equal(host.getSnapshot().windows.length,count+1);
assert.equal(host.dispatchInput({kind:'files',action:'open',target:'home'}),true);
assert.equal(host.getSnapshot().windows.at(-1).application,'warlock-files');
const peerCount=host.getSnapshot().windows.length, peerId=host.getSnapshot().windows.at(-1).id;
assert.equal(host.dispatchInput({kind:'files',action:'open',target:'/home/demo/documents'}),true);
assert.equal(host.getSnapshot().windows.length,peerCount);
assert.equal(host.getSnapshot().windows.at(-1).id,peerId);
assert.equal(host.dispatchInput({kind:'window',action:'close',epoch:host.getSnapshot().epoch,windowId:peerId,incarnation:host.getSnapshot().windows.at(-1).incarnation}),true);
assert.equal(host.dispatchInput({kind:'application',action:'launch',intent:{entry:'warlock-browser'}}),true);
assert.ok(BigInt(host.getSnapshot().windows.at(-1).id)>BigInt(peerId));
assert.equal(await host.invoke('unknown-intent'),false);
host.destroy();
assert.equal(listeners.has('message'),false);
console.log('Host envelope, topology, snapshot and epoch checks passed.');
